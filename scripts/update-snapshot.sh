#!/usr/bin/env bash
# Regenerates js/repos-snapshot.js from your public GitHub repos (requires gh).
# The site also refreshes this data live from the GitHub API in the browser;
# the snapshot is the fallback when the API is unavailable or rate-limited.
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "/* Generated by scripts/update-snapshot.sh on $(date +%Y-%m-%d). Do not edit by hand. */"
  printf 'window.REPOS_SNAPSHOT = '
  gh repo list jeffnyman --limit 500 --visibility public --source \
    --json name,description,homepageUrl,primaryLanguage,stargazerCount,pushedAt,isArchived,repositoryTopics \
    --jq '[.[] | {name, description: (.description // ""), homepage: (.homepageUrl // ""), language: (.primaryLanguage.name // ""), stars: .stargazerCount, pushed: .pushedAt, archived: .isArchived, topics: [.repositoryTopics[]?.name]}] | sort_by(.pushed) | reverse'
  echo ";"
} > js/repos-snapshot.js
echo "Wrote js/repos-snapshot.js"
